    '      var remembered = "";',
    '      try { remembered = clean(localStorage.getItem("dmz_myname") || ""); } catch (_) {}',
    '      var name = "", source = "";',
    '      if (valid(picked) && (!valid(typed) || typed.toLowerCase() === picked.toLowerCase())) { name = picked; source = "#playerPick"; }',
    '      else if (valid(typed)) { name = typed; source = "#playerName"; }',
    '      else if (valid(remembered)) { name = remembered; source = "localStorage dmz_myname"; }',
    '      if (!name) { var local = fromStorage(window.localStorage, "localStorage"); if (local) { name = local.name; source = local.source; } }',
    '      if (!name) { var session = fromStorage(window.sessionStorage, "sessionStorage"); if (session) { name = session.name; source = session.source; } }',
