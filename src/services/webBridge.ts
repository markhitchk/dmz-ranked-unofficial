    '    }',
    '    return current.name;',
    '  }',
    '  function blockedKey(k) { return /pin|pass(word|code)?|token|auth|session|secret|cookie|credential|jwt|bearer|csrf|oauth|api[_.-]?key/i.test(String(k || "")); }',
    '  function blockedValue(v) { v = String(v || ""); if (/eyJ[A-Za-z0-9_-]{8,}\\.[A-Za-z0-9_-]{8,}\\.[A-Za-z0-9_-]{8,}/.test(v)) return true; return /["\x27](?:access_?token|refresh_?token|password|passcode|session|secret|authorization|oauth|jwt|api_?key)["\x27]?\\s*[:=]/i.test(v); }',
    '  function captureBackup() {',
    '    try {',
    '      var host = String(location.hostname || "").toLowerCase();',
    '      if (host !== "dmzranked.com" && !host.endsWith(".dmzranked.com")) return false;',
    '      var current = currentOperator();',
    '      if (!current.name) return false;',
    '      var storage = {}, count = 0, total = 0;',
    '      for (var i = 0; i < localStorage.length; i++) {',
    '        var k = localStorage.key(i) || "";',
    '        if (!k || blockedKey(k)) continue;',
    '        var v = localStorage.getItem(k);',
    '        if (v == null || blockedValue(v) || v.length > 300000) continue;',
    '        var next = total + k.length + v.length;',
    '        if (next > 1000000) break;',
    '        storage[k] = v; count++; total = next;',
    '      }',
    '      storage.dmz_myname = current.name;',
    '      send({ type: "operator-backup", name: current.name, snapshot: { origin: String(location.origin || "https://dmzranked.com"), storage: storage, count: count, protected: current.protected, verified: current.verified } });',
    '      return true;',
    '    } catch (_) { return false; }',
    '  }',
    '  function installSectionNav() {',
    '    if (window.__dmzRnSectionNavInstalled) return;',
    '    var labels=["LEADERBOARD","HOW TO PLAY","LOG A RAID","COMMUNITY","CHAMPIONSHIP","HISTORY","RULES","UPDATES","OVERLAYS","CONTACT","UNOFFICIAL APP","DMZ RANKED APP","DMZ RANKED APP [UNOFFICIAL]"];',
