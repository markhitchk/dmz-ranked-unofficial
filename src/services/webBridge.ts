    '          if (child && typeof child === "object") { var nestedChild = fromObject(child, depth + 1); if (nestedChild) return nestedChild; }',
    '        }',
    '        return "";',
    '      }',
    '      function fromStorage(storage, label) {',
    '        try {',
    '          for (var i = 0; i < storage.length; i++) {',
    '            var key = storage.key(i) || "";',
