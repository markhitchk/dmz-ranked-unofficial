    '    function detect(){var list=candidates();for(var i=0;i<list.length;i++){var el=list[i],lab=labelFrom(el);if(!lab)continue;var cls=norm(el.className),aria="";try{aria=norm(el.getAttribute("aria-selected"));}catch(_){}if(aria==="TRUE"||cls.indexOf("ACTIVE")>=0||cls.indexOf("SELECTED")>=0||cls.indexOf("CURRENT")>=0)return lab;}return "LEADERBOARD";}',
    '    var initial=detect(); window.__dmzRnSectionNav={stack:[initial],current:initial,suppress:false};',
    '    document.addEventListener("click",function(ev){var st=window.__dmzRnSectionNav;if(!st||st.suppress)return;var lab=labelFrom(ev.target);if(!lab)return;setTimeout(function(){if(!st.suppress&&st.current!==lab){st.stack.push(lab);st.current=lab;}},0);},true);',
    '    window.__dmzRnSectionBack=function(){try{var st=window.__dmzRnSectionNav;if(!st||st.stack.length<=1)return "empty";st.stack.pop();var prev=st.stack[st.stack.length-1],control=findControl(prev);if(!control)return "missing";st.current=prev;st.suppress=true;control.click();setTimeout(function(){st.suppress=false;},120);return "handled";}catch(_){return "error";}};',
